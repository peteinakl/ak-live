// scripts/build.mjs — Builds dist/ for the Cloudflare Worker's static assets.
// Copies an explicit allowlist only, so secrets, proxy.js, docs and tests can
// never be uploaded by accident. Run with: node scripts/build.mjs

import { cp, rm, mkdir, writeFile, readdir, readFile } from 'node:fs/promises';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const DIST = join(ROOT, 'dist');
const ALLOWLIST = ['index.html', 'css', 'js'];
const SERVER_ONLY = ['AT_API_KEY', 'OPENSKY_CLIENT_ID', 'OPENSKY_CLIENT_SECRET', 'TOMTOM_API_KEY'];

const { CONFIG } = await import(join(ROOT, 'config.local.js'));

await rm(DIST, { recursive: true, force: true });
await mkdir(DIST);
for (const entry of ALLOWLIST) await cp(join(ROOT, entry), join(DIST, entry), { recursive: true });

// Browser config: domain-restricted tile keys only. Traffic goes via the Worker.
const publicConfig = {
  MAPTILER_KEY: CONFIG.MAPTILER_KEY,
  LINZ_API_KEY: CONFIG.LINZ_API_KEY,
  TRAFFIC_PROXY: true,
  // Free ADS-B sources all refuse Cloudflare's network; see worker/index.js.
  FLIGHTS: false,
};
await writeFile(join(DIST, 'config.local.js'),
  `// Generated by scripts/build.mjs — public keys only.\nexport const CONFIG = ${JSON.stringify(publicConfig, null, 2)};\n`);

// Belt and braces: fail if any server-only secret ended up in the bundle.
const secrets = SERVER_ONLY.map(k => CONFIG[k]).filter(v => v && !v.startsWith('YOUR_'));
const files = (await readdir(DIST, { recursive: true, withFileTypes: true })).filter(d => d.isFile());
for (const file of files) {
  const path = join(file.parentPath, file.name);
  const text = await readFile(path, 'utf8');
  if (secrets.some(s => text.includes(s))) {
    await rm(DIST, { recursive: true, force: true });
    throw new Error(`Server-only secret found in ${path} — build aborted`);
  }
}
console.log(`[build] dist/ ready: ${files.length} files, secrets check passed`);
